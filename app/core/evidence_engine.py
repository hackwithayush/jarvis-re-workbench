"""
JARVIS RE — Unified Evidence & Correlation Engine v2.0
Central intelligence engine for cross-tool correlation, deduplication, and evidence evaluation:
- Normalizes findings across Native parsers, DIE, radare2, Ghidra, ILSpy, capa, YARA, and Sandbox.
- Deduplicates equivalent findings while preserving source tool provenance.
- Evaluates multi-dimensional analysis coverage (static, function recovery, dynamic execution).
- Evidence-grounded verdict determination:
  * Never infers safety from missing evidence or low entropy.
  * Emits explicitly provisional/inconclusive verdicts when coverage is incomplete.
  * Distinguishes deliberate malice from build anomalies (future timestamps, clock skew).
- Transparent confidence scoring with documented reasoning.
"""

from typing import Any, Dict, List, Optional, Set, Tuple
from app.core.schema import AIHypothesis, Finding, FindingStatus, FindingType


class EvidenceCorrelationEngine:
    """Correlates multi-tool findings and generates explainable, coverage-aware hypotheses and verdicts."""

    @staticmethod
    def correlate(
        findings: List[Finding],
        imphash: Optional[str] = None,
        entropy: float = 0.0,
        is_dotnet: bool = False,
        functions_count: int = 0,
        dynamic_executed: bool = False,
        tool_executions: Optional[Dict[str, Any]] = None,
    ) -> Tuple[List[Finding], List[AIHypothesis], Dict[str, Any]]:
        """
        Deduplicate findings, cross-reference tool outputs, enforce provenance,
        and generate evidence-grounded hypotheses with coverage-calibrated verdicts.
        """
        deduped: List[Finding] = []
        seen_keys: Set[str] = set()

        benign_indicators: List[str] = []
        suspicious_indicators: List[str] = []
        hypotheses: List[AIHypothesis] = []

        # 1. Deduplication & Provenance pass
        for f in findings:
            # Ensure every finding has an explicit location reference
            if not f.address_or_location:
                f.address_or_location = f"meta:{f.finding_type.value}:{f.name}"

            # Ensure confidence reasoning exists
            if not f.confidence_reasoning:
                f.confidence_reasoning = f"Generated by {f.source_tool} ({f.tool_version}) for category '{f.name}'."

            # Key based on type, normalized name, and address
            key = f"{f.finding_type}:{f.name.lower()}:{f.address_or_location}"
            if key in seen_keys:
                # Corroborate existing finding
                for existing in deduped:
                    if f"{existing.finding_type}:{existing.name.lower()}:{existing.address_or_location}" == key:
                        existing_sources = [e.source for e in existing.evidence]
                        if f.source_tool not in existing_sources:
                            existing.evidence.append(
                                type(existing.evidence[0])(source=f.source_tool, content=f.description)
                                if existing.evidence else None
                            ) if hasattr(existing, "evidence") else None
                            existing.confidence = min(0.99, existing.confidence + 0.05)
                            existing.confidence_reasoning += f" Corroborated by {f.source_tool}."
                            existing.verification_status = FindingStatus.CORROBORATED
                continue

            seen_keys.add(key)
            deduped.append(f)

        # 2. Extract key signals
        suspicious_apis = [f for f in deduped if f.name == "suspicious_api" or "suspicious_import" in f.name]
        network_strings = [f for f in deduped if f.name in ("network_url", "network_ip")]
        compilers = [f for f in deduped if f.finding_type == FindingType.COMPILER]
        high_entropy_sections = [
            f for f in deduped
            if f.finding_type == FindingType.SECTION and f.raw_data.get("entropy", 0) > 7.1
        ]
        anti_debug = [
            f for f in suspicious_apis
            if any(term in f.description for term in ("IsDebuggerPresent", "CheckRemoteDebuggerPresent", "NtQueryInformationProcess"))
        ]
        anomalies = [f for f in deduped if f.finding_type == FindingType.ANOMALY]

        # 3. Correlation Rules & Hypothesis Generation

        # Hypothesis A: Potential Payload Unpacking or Memory Injection
        if high_entropy_sections and any(
            term in f.description for f in suspicious_apis
            for term in ("VirtualAlloc", "WriteProcessMemory", "NtCreateThreadEx")
        ):
            hypotheses.append(
                AIHypothesis(
                    category="Memory Injection / Unpacking",
                    title="Suspicious Memory Manipulation with High-Entropy Payload",
                    description=(
                        f"Sample contains {len(high_entropy_sections)} high-entropy section(s) combined with memory allocation "
                        "APIs (VirtualAlloc/WriteProcessMemory). This pattern commonly indicates a self-extracting packer, "
                        "crypter, or runtime memory injector."
                    ),
                    confidence=0.88,
                    supporting_evidence_ids=[f.id for f in (high_entropy_sections + suspicious_apis)[:5]],
                )
            )
            suspicious_indicators.append(
                f"Memory allocation combined with high section entropy ({len(high_entropy_sections)} packed sections)"
            )

        # Hypothesis B: Network Command & Control or Telemetry Exfiltration
        if network_strings and any(
            term in f.description for f in suspicious_apis
            for term in ("Internet", "WSA", "connect", "URLDownload", "HttpSendRequest")
        ):
            hypotheses.append(
                AIHypothesis(
                    category="Network Communication",
                    title="Active Network Connection Capability with Embedded Endpoints",
                    description=(
                        f"Sample contains embedded network endpoints ({len(network_strings)} URLs/IPs) along with Win32 network "
                        "APIs. This indicates active outbound HTTP(S) or socket communication capability."
                    ),
                    confidence=0.85,
                    supporting_evidence_ids=[f.id for f in (network_strings + suspicious_apis)[:5]],
                )
            )
            suspicious_indicators.append(
                f"Embedded network endpoints ({len(network_strings)}) correlated with socket APIs"
            )

        # Hypothesis C: Anti-Analysis and Evasion
        if anti_debug:
            hypotheses.append(
                AIHypothesis(
                    category="Anti-Analysis",
                    title="Debugger Evasion Mechanisms Present",
                    description=(
                        f"Sample references anti-debugging inspection APIs ({', '.join(f.name for f in anti_debug[:3])}). "
                        "It may alter execution flow when analyzed inside a debugger or sandbox."
                    ),
                    confidence=0.82,
                    supporting_evidence_ids=[f.id for f in anti_debug],
                )
            )
            suspicious_indicators.append(f"Anti-debugging API calls detected ({len(anti_debug)} indicators)")

        # Record factual benign observations
        if compilers:
            benign_indicators.append(f"Recognized compiler/toolchain: {', '.join(c.name for c in compilers[:3])}")
        if entropy < 6.8:
            benign_indicators.append(f"Normal overall executable Shannon entropy ({entropy:.2f} / 8.000)")

        # 4. Rigorous Coverage Assessment
        coverage_factors = []
        coverage_score = 0.0

        # Static format inspection (30%)
        coverage_score += 0.30
        coverage_factors.append("Static header and section analysis completed")

        # Function / Code Recovery (35%)
        if functions_count > 0:
            coverage_score += 0.35
            coverage_factors.append(f"Function recovery successful ({functions_count} routines analyzed)")
        elif is_dotnet:
            coverage_factors.append("Managed .NET executable: native function recovery is 0 (delegated to CLR runtime)")
        else:
            coverage_factors.append("Native function recovery yielded 0 functions (code unanalyzed)")

        # Dynamic execution (35%)
        if dynamic_executed:
            coverage_score += 0.35
            coverage_factors.append("Dynamic sandbox runtime behavioral trace completed")
        else:
            coverage_factors.append("Dynamic sandbox execution NOT performed (static triage only)")

        coverage_score = round(coverage_score, 2)
        coverage_level = (
            "COMPREHENSIVE" if coverage_score >= 0.85 else (
                "PARTIAL_CODE_ANALYSIS" if coverage_score >= 0.50 else "INCOMPLETE_STATIC_ONLY"
            )
        )

        # 5. Evidence-Aware Verdict Determination
        # Rule: Never return LIKELY_BENIGN if coverage is incomplete, functions are 0, or dynamic execution is absent.
        if suspicious_indicators and len(hypotheses) >= 2:
            verdict = "SUSPICIOUS"
            verdict_confidence = 0.85
            rationale = "Corroborated multiple suspicious behavioral patterns: " + "; ".join(suspicious_indicators)
        elif suspicious_indicators:
            verdict = "INVESTIGATE"
            verdict_confidence = 0.75
            rationale = "Isolated suspicious indicator(s) identified requiring manual inspection: " + "; ".join(suspicious_indicators)
        elif anomalies:
            verdict = "INCONCLUSIVE_ANOMALIES_PRESENT"
            verdict_confidence = 0.60
            top_anomaly = anomalies[0].description
            rationale = (
                f"Binary contains {len(anomalies)} structural/metadata anomaly/anomalies "
                f"({top_anomaly[:120]}...). Not inherently malicious, but requires verification."
            )
        elif not dynamic_executed or functions_count == 0:
            verdict = "PROVISIONAL_INCONCLUSIVE"
            verdict_confidence = 0.45
            rationale = (
                "PROVISIONAL ASSESSMENT: No malicious indicators detected in static headers, "
                f"but analysis coverage is incomplete ({coverage_level}, coverage score: {int(coverage_score * 100)}%). "
                "No dynamic behavioral execution trace was performed and 0 native routines were analyzed. "
                "Absence of suspicious imports or normal entropy does NOT constitute evidence of safety."
            )
        else:
            verdict = "LIKELY_BENIGN"
            verdict_confidence = 0.85
            rationale = "Comprehensive static, disassembly, and runtime analysis completed with no suspicious indicators."

        assessment = {
            "verdict": verdict,
            "confidence": verdict_confidence,
            "rationale": rationale,
            "coverage_level": coverage_level,
            "coverage_score": coverage_score,
            "coverage_factors": coverage_factors,
            "benign_indicators": benign_indicators,
            "suspicious_indicators": suspicious_indicators,
            "anomalies_count": len(anomalies),
            "hypotheses_count": len(hypotheses),
            "correlation_summary": (
                f"Correlated {len(deduped)} deduplicated findings across {len(seen_keys)} distinct signals. "
                f"Coverage: {coverage_level} ({int(coverage_score * 100)}%). Assessment verdict: {verdict}."
            ),
        }

        return deduped, hypotheses, assessment
