"""
Jarvis RE — Technical Report Generator
Generates evidence-backed technical reports in JSON, Markdown, and standalone HTML formats.
Adheres strictly to the Stark / Jarvis dark theme and visual identity.
"""

import json
import os
from datetime import datetime, timezone
from typing import Any, Dict, List, Optional


class ReportGenerator:
    """Produces multi-format analysis reports from normalized evidence records."""

    def __init__(self, template_dir: Optional[str] = None):
        self.template_dir = template_dir or os.path.join(os.path.dirname(__file__), "templates")

    def generate_report(
        self,
        sample_info: Dict[str, Any],
        findings: List[Dict[str, Any]],
        jobs: Optional[List[Dict[str, Any]]] = None,
        report_format: str = "json",
    ) -> str:
        """
        Generate a comprehensive analysis report.
        Args:
            sample_info: Metadata dictionary for the analysed binary.
            findings: Normalized finding records.
            jobs: Job history records.
            report_format: 'json', 'markdown', or 'html'.
        """
        jobs = jobs or []
        summary = self._build_summary(findings)

        report_payload = {
            "title": f"Binary Analysis Report — {sample_info.get('filename', 'Unknown')}",
            "generated_at": datetime.now(timezone.utc).isoformat(),
            "sample": sample_info,
            "summary": summary,
            "findings": findings,
            "jobs": jobs,
            "disclaimer": (
                "CONFIDENTIAL & TECHNICAL FORENSICS: This report contains static/dynamic observations "
                "generated by automated reverse-engineering engines. Inferences and hypotheses are labeled "
                "'unverified' until reviewed by a qualified security analyst."
            ),
        }

        fmt = report_format.lower()
        if fmt == "json":
            return json.dumps(report_payload, indent=2, default=str)
        elif fmt in ["markdown", "md"]:
            return self._generate_markdown(report_payload)
        elif fmt == "html":
            return self._generate_html(report_payload)
        else:
            raise ValueError(f"Unsupported report format: {report_format}")

    def _build_summary(self, findings: List[Dict[str, Any]]) -> Dict[str, Any]:
        """Compute aggregate metrics across findings."""
        by_type: Dict[str, int] = {}
        by_tool: Dict[str, int] = {}
        by_status: Dict[str, int] = {}
        high_confidence = 0

        for f in findings:
            ft = f.get("finding_type", "unknown")
            by_type[ft] = by_type.get(ft, 0) + 1

            st = f.get("source_tool", "unknown")
            by_tool[st] = by_tool.get(st, 0) + 1

            status = f.get("status", "unverified")
            by_status[status] = by_status.get(status, 0) + 1

            if float(f.get("confidence", 0.0)) >= 0.8:
                high_confidence += 1

        return {
            "total_findings": len(findings),
            "findings_by_type": by_type,
            "findings_by_tool": by_tool,
            "findings_by_status": by_status,
            "high_confidence_count": high_confidence,
        }

    def _generate_markdown(self, payload: Dict[str, Any]) -> str:
        s = payload["sample"]
        sum_data = payload["summary"]
        findings = payload["findings"]

        lines = [
            f"# {payload['title']}",
            f"*Generated at: {payload['generated_at']}*",
            "",
            "> **NOTICE:** " + payload["disclaimer"],
            "",
            "## 1. Sample Identity & Integrity",
            f"- **Filename:** `{s.get('filename')}`",
            f"- **File Size:** {s.get('file_size', 0):,} bytes",
            f"- **Format:** `{s.get('file_type', 'Unknown')}`",
            f"- **Architecture:** `{s.get('architecture', 'Unknown')}`",
            f"- **SHA-256:** `{s.get('sha256')}`",
            f"- **MD5:** `{s.get('md5')}`",
            f"- **SHA-1:** `{s.get('sha1')}`",
            "",
            "## 2. Analysis Metrics & Triage",
            f"- **Total Evidence Items:** {sum_data['total_findings']}",
            f"- **High-Confidence Findings (>= 80%):** {sum_data['high_confidence_count']}",
            "",
            "### Findings by Category",
            "| Category | Count |",
            "|---|---|",
        ]
        for k, v in sum_data["findings_by_type"].items():
            lines.append(f"| `{k}` | {v} |")

        lines.extend([
            "",
            "### Findings by Source Engine",
            "| Tool | Count |",
            "|---|---|",
        ])
        for k, v in sum_data["findings_by_tool"].items():
            lines.append(f"| `{k}` | {v} |")

        lines.extend([
            "",
            "## 3. Findings & Evidence Inventory",
            "| Location | Type | Name | Engine | Conf. | Description |",
            "|---|---|---|---|---|---|",
        ])

        for f in findings:
            addr = f.get("address") or "—"
            ftype = f.get("finding_type", "")
            fname = (f.get("name") or "unnamed")[:30]
            tool = f.get("source_tool", "")
            conf = f"{float(f.get('confidence', 0.5)) * 100:.0f}%"
            desc = (f.get("description") or "").replace("|", "\\|")[:80]
            lines.append(f"| `{addr}` | `{ftype}` | {fname} | `{tool}` | {conf} | {desc} |")

        return "\n".join(lines)

